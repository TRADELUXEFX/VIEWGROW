-- ViewGrow: VIP contacts. Numbers the admin chooses, saved on a member's phone (with the name the admin typed)
-- once the member allows Contacts. Safe to run twice.
-- Run once in the Supabase SQL Editor. Adds ONE table and FOUR functions. Changes no existing table or function.
--
-- WHY: until now the app saved only the admin's own number ("ViewGrow Admin"). The admin can now keep a list of
-- VIP contacts (a name + a number each) and the app saves every one of them on the member's phone, named exactly
-- as the admin typed it (no " VG" added, no ViewGrow note, so Delete My Contacts and a ban leave them alone).
--
-- Table web_vip_contacts: id, name, phone (digits with country code, unique), created_at.
--   Row level security is on and no one can read or write it directly: only the functions below can.
--
-- web_admin_vip_list(p_key)                      -> {ok, rows:[{id, name, phone}]}            (admin key)
-- web_admin_vip_save(p_key, p_name, p_phone, p_id default null)
--                                               -> {ok, id}   adds a VIP (p_id empty) or changes one (p_id given)
--                                                  errors: BAD_NAME, BAD_PHONE, DUPLICATE, NOT_FOUND
-- web_admin_vip_delete(p_key, p_id)              -> {ok}       removes one VIP from the list only
-- web_vip_numbers(p_phone, p_pin)               -> {ok, contacts:[{name, phone}]}            (a logged-in member)
--   Wrong number / password / token: the same {ok:false, code} answers as every other member function.
--
-- Phone rule: digits only. 0803 456 7890 and 803 456 7890 become 2348034567890. A number that already starts
-- with a country code is kept (international VIPs work). It must end up 10 to 15 digits long.
--
-- BEFORE RUNNING (STATE.md rule 2): run the read-only check in changelog.md for 20261119160000. The guard below
-- also stops with an error, changing nothing, if _web_admin_ok or _web_auth is missing.

do $$
begin
  if to_regprocedure('public._web_admin_ok(text)') is null then
    raise exception '_web_admin_ok(text) is missing. Nothing was changed.';
  end if;
  if to_regprocedure('public._web_auth(text,text)') is null then
    raise exception '_web_auth(text,text) is missing. Nothing was changed.';
  end if;
end $$;

create table if not exists public.web_vip_contacts (
  id         bigint generated by default as identity primary key,
  name       text        not null,
  phone      text        not null unique,
  created_at timestamptz not null default now()
);
alter table public.web_vip_contacts enable row level security;
revoke all on public.web_vip_contacts from anon, authenticated;

-- Admin: the list, oldest first.
create or replace function public.web_admin_vip_list(p_key text)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  k text := public._web_admin_ok(p_key);
begin
  if k <> 'OK' then return jsonb_build_object('ok', false, 'code', k); end if;
  return jsonb_build_object('ok', true, 'rows', coalesce((
    select jsonb_agg(jsonb_build_object('id', v.id, 'name', v.name, 'phone', v.phone) order by v.id)
      from public.web_vip_contacts v), '[]'::jsonb));
end
$function$;

-- Admin: add one (p_id empty) or change one (p_id given).
create or replace function public.web_admin_vip_save(p_key text, p_name text, p_phone text, p_id bigint default null)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  k text := public._web_admin_ok(p_key);
  n text := btrim(regexp_replace(coalesce(p_name, ''), '[[:cntrl:]]+', ' ', 'g'));
  d text := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  v_id bigint;
begin
  if k <> 'OK' then return jsonb_build_object('ok', false, 'code', k); end if;
  if char_length(n) < 1 or char_length(n) > 60 then
    return jsonb_build_object('ok', false, 'code', 'BAD_NAME');
  end if;
  if d ~ '^0\d{10}$' then d := '234' || substr(d, 2);
  elsif d ~ '^[789]\d{9}$' then d := '234' || d;
  end if;
  if d !~ '^\d{10,15}$' then
    return jsonb_build_object('ok', false, 'code', 'BAD_PHONE');
  end if;

  if p_id is null then
    insert into public.web_vip_contacts (name, phone) values (n, d) returning id into v_id;
  else
    update public.web_vip_contacts set name = n, phone = d where id = p_id returning id into v_id;
    if v_id is null then return jsonb_build_object('ok', false, 'code', 'NOT_FOUND'); end if;
  end if;
  return jsonb_build_object('ok', true, 'id', v_id);
exception when unique_violation then
  return jsonb_build_object('ok', false, 'code', 'DUPLICATE');
end
$function$;

-- Admin: take one off the list. (Phones that already saved it keep it; nothing is removed from any phone.)
create or replace function public.web_admin_vip_delete(p_key text, p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  k text := public._web_admin_ok(p_key);
  v_n int;
begin
  if k <> 'OK' then return jsonb_build_object('ok', false, 'code', k); end if;
  delete from public.web_vip_contacts where id = p_id;
  get diagnostics v_n = row_count;
  if v_n = 0 then return jsonb_build_object('ok', false, 'code', 'NOT_FOUND'); end if;
  return jsonb_build_object('ok', true);
end
$function$;

-- Member (the app): the list to save on this phone.
create or replace function public.web_vip_numbers(p_phone text, p_pin text)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  a record;
begin
  select * into a from public._web_auth(p_phone, p_pin);
  if a.err is not null then return a.err; end if;
  return jsonb_build_object('ok', true, 'contacts', coalesce((
    select jsonb_agg(jsonb_build_object('name', v.name, 'phone', v.phone) order by v.id)
      from public.web_vip_contacts v), '[]'::jsonb));
end
$function$;

revoke all on function public.web_admin_vip_list(text) from public;
grant execute on function public.web_admin_vip_list(text) to anon, authenticated;
revoke all on function public.web_admin_vip_save(text, text, text, bigint) from public;
grant execute on function public.web_admin_vip_save(text, text, text, bigint) to anon, authenticated;
revoke all on function public.web_admin_vip_delete(text, bigint) from public;
grant execute on function public.web_admin_vip_delete(text, bigint) to anon, authenticated;
revoke all on function public.web_vip_numbers(text, text) from public;
grant execute on function public.web_vip_numbers(text, text) to anon, authenticated;
